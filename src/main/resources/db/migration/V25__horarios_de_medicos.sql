-- ----------------------------------------------------------------------------
-- HU-29 · Asignacion de medicos a una clinica, con dias y horarios (DRS-97).
--
-- clinica_personal (V10) dice EN QUE sede trabaja alguien, pero no CUANDO.
-- Sin el cuando no hay "franja disponible" sobre la que agendar (HU-30) ni
-- forma de detectar que un medico esta en dos sedes a la misma hora.
--
-- Un medico puede tener varias franjas por dia y por sede. Que dos franjas
-- del mismo medico no se traslapen -en la misma sede o en otra- lo valida el
-- servicio, con un mensaje que nombra el conflicto (criterio 2); una
-- restriccion de exclusion daria un error sin esa informacion.
-- ----------------------------------------------------------------------------

CREATE TABLE public.horarios_de_medico (
    horario_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_user_id  INTEGER NOT NULL
        REFERENCES public.users (user_id) ON DELETE CASCADE,
    clinica_id      INTEGER NOT NULL
        REFERENCES public.clinicas (clinica_id) ON DELETE CASCADE,
    -- 1 = lunes ... 7 = domingo, como java.time.DayOfWeek.
    dia_semana      SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    hora_inicio     TIME NOT NULL,
    hora_fin        TIME NOT NULL,
    CONSTRAINT horarios_de_medico_rango_ck CHECK (hora_fin > hora_inicio)
);

CREATE INDEX horarios_de_medico_medico_dia_idx ON public.horarios_de_medico (medico_user_id, dia_semana);
CREATE INDEX horarios_de_medico_clinica_idx    ON public.horarios_de_medico (clinica_id);
